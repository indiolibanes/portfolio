assert.match(script, /stop\('Player fechado/);
assert.match(script, /if \(document.hidden && loaded\)/);

// A mudança entre opções e player compacto não pode remover/recriar o iframe.
const optionsHandler = script.match(/optionsToggle\.addEventListener\('click',[\s\S]*?\n  \}\);/)?.[0];
const sideHandler = script.match(/sideToggle\.addEventListener\('click',[\s\S]*?\n  \}\);/)?.[0];
assert.ok(optionsHandler, 'options handler must exist');
assert.ok(sideHandler, 'side handler must exist');
assert.doesNotMatch(optionsHandler, /replaceChildren|stop\(|createElement/);
assert.doesNotMatch(sideHandler, /replaceChildren|stop\(|createElement/);
assert.match(css, /min-width:200px/);
assert.match(css, /min-height:200px/);
assert.match(css, /\[hidden\]\{display:none!important\}/);
assert.match(css, /\[data-soundtrack-mode=docked\]/);
assert.match(css, /\[data-soundtrack-side=left\]/);
assert.match(headers, /frame-src https:\/\/www\.youtube-nocookie\.com https:\/\/www\.youtube\.com/);
assert.match(readme, /### Trilha oficial: Ode to Hsin and Moon/);
assert.match(readme, /Player de canto/);
assert.match(readme, /a música pode continuar tocando|pode continuar tocando/i);
assert.doesNotMatch(component, /<audio\b|<video\b|\.mp3\b|\.ogg\b|\.wav\b/);
assert.doesNotMatch(script, /fetch\(|AudioContext|new Audio\(/);
console.log('Hsin soundtrack: visible persistent compact dock, full/highlight/silence, movable UI, no iframe reset on options, YouTube policies, attribution PASS');
